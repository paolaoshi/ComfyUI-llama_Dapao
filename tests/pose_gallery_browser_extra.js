async (page) => {
    await page.getByRole('button',{name:'放大查看当前姿势'}).click();
    await page.getByRole('button',{name:'下一视角',exact:true}).click();
    await page.getByRole('button',{name:'+',exact:true}).click();
    await page.getByRole('button',{name:'适应窗口',exact:true}).click();
    await page.keyboard.press('Escape');
    await page.waitForFunction(()=>document.querySelectorAll('dialog').length === 1);
    await page.getByRole('button',{name:'使用指南与来源'}).click();
    await page.keyboard.press('Escape');
    await page.waitForFunction(()=>document.querySelectorAll('dialog').length === 1);
    await page.getByRole('button',{name:'全身单人・标准系 · 73 组 / 365 张'}).click();
    await page.getByRole('button',{name:'加载更多（剩余 43）'}).click();
    if (await page.locator('article').count() !== 60) throw Error('pagination');
    await page.getByRole('combobox',{name:'动作分类'}).selectOption({label:'站姿'});
    const download = page.waitForEvent('download');
    await page.getByRole('button',{name:'下载参考图'}).click();
    if (!(await download).suggestedFilename().endsWith('.webp')) throw Error('download');
    await page.setViewportSize({width:390,height:844});
    await page.getByRole('textbox',{name:'搜索姿势'}).fill('P017');
    await page.getByRole('combobox',{name:'动作分类'}).selectOption('');
    await page.locator('.dp-card-image').first().click();
    if (await page.locator('dialog').evaluate(e=>e.scrollWidth>e.clientWidth+2)) throw Error('mobile overflow');
    await page.screenshot({path:'output/playwright/pose-mobile.png'});
    await page.setViewportSize({width:1440,height:1000});
    await page.getByRole('textbox',{name:'搜索姿势'}).fill('');
    await page.screenshot({path:'output/playwright/pose-desktop.png'});
    await page.getByRole('button',{name:'关闭',exact:true}).click();
    await page.route('**/dapao/pose-gallery/catalog',route=>route.fulfill({status:500,body:'failure'}));
    await page.reload();
    await page.getByRole('button',{name:'打开测试图库'}).click();
    await page.getByRole('button',{name:'重试读取目录'}).waitFor();
    await page.unroute('**/dapao/pose-gallery/catalog');
    await page.getByRole('button',{name:'重试读取目录'}).click();
    await page.getByRole('button',{name:'全身单人・标准系 · 73 组 / 365 张'}).click();
    await page.route('**/dapao/pose-gallery/image/*',route=>route.abort());
    await page.getByRole('button',{name:'下一姿势',exact:true}).click();
    await page.getByRole('button',{name:/使用此视角/}).click();
    await page.getByRole('status').filter({hasText:'原输出已保留'}).waitFor();
    await page.getByRole('button',{name:'关闭',exact:true}).click();
    if (!(await page.locator('#selection').textContent()).includes('full_single_P001_front')) throw Error('failure replaced selection');
    await page.unroute('**/dapao/pose-gallery/image/*');
    console.log('PASS zoom, help, pagination, category, download, mobile, catalog retry, failure preserves selection');
}
