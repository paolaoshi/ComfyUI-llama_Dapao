def panel_blueprint(style, layout, count, reading):
    """Provide flexible reading guidance, leaving art direction to the Skill."""
    expressive = {
        '斜切速度分镜':'用倾斜对角边框、楔形与梯形格沿动作轴线排列，大小疏密明显变化；保留白色沟槽和清楚阅读路径，优先体现斜切方向，避免仅有水平矩形。',
        '主镜头大格':'选择剧情高潮作为占页面约一半的主镜头大格，其他格为铺垫、细节、反应和余韵；远景与特写有明显尺度差，不把每格平均切分。',
        '人物破框叠层':'一个高潮格中的人物头部、手臂或关键道具越过本格边框，遮挡一小段白色沟槽或相邻格边缘；身体主体仍属于原格，只绘制一次，通过边框在人物轮廓下中断明确表现破框。根据叙事需要安排遮挡，优先保证关键动作和对白可读。',
        '强透视冲击分镜':'关键大格采用近大远小的广角透视，前景手掌/道具/脚明显放大、身体与背景向消失点收缩，辅以仰视或俯冲镜头和速度线；保持肢体连接，避免整页同一平视中景。',
        '跨格连续场景':'用连续的同一环境跨过数格建立大场景，分格切分时间或视线，背景透视与地平线连续；明确每格所属时刻，不能把同一个人误画成同一时刻的分身。',
        '插入特写分镜':'在主镜头周边安排道具/手部/眼神的插入小格，所有插入格计入总数；插格只遮挡非关键背景，形成动作原因、细节与结果，不重复主角头像凑格。',
        '自由混合分镜':'根据故事组合斜切小格、一个主镜头大格、强透视和一次人物破框，形成铺垫—升级—爆点—反应的视觉节奏；主格主体轮廓可压过边框，格子主体位置仍清楚、对白不被遮挡，不做均匀网格。',
    }
    expressive.update({'无框留白分镜': '用留白、景物和人物视线组织无边框镜头，画面可自然融接，阅读节拍由疏密和尺度变化体现。', '跨页全景分镜': '用宽阔的跨页式全景建立空间，在适合处穿插人物与细节镜头，形成宏观场面与近景叙事的呼应。', '蒙太奇时间流': '通过重复道具、环境变化与人物动作串联不同时间片段，让镜头之间有明确时间推进和情绪累积。', '对称对照分镜': '用呼应或镜像布局对比过去与现在、两个人物或两种选择，构图相似但信息发生变化。', '环形视线分镜': '围绕核心画面安排环形或旋转式镜头，借人物视线、动作和文字位置引导顺序，自然抵达视觉中心。', '长镜头连续动作': '保持连贯环境和视角轴线，在相邻镜头延续动作全过程，借人物位置变化呈现长镜头般的时间流动。'})
    if layout in expressive:
        amount = f'准确{count}格，所有插格也计入总数。' if count else '按故事实际节拍自行确定格数，不套用固定六格或五至七格模板。'
